/**
 * Deterministic, dependency-free string hash used ONLY to avoid storing
 * plaintext demo passwords in AsyncStorage. This is NOT a secure password
 * hash (no salt, no slow KDF) — do not reuse this for a real backend. Real
 * auth (Phase 3 "for real") should go through Supabase Auth / another
 * provider once one is provisioned; see services/auth.ts's header comment.
 */
export function demoHash(input: string): string {
  let h1 = 0xdeadbeef ^ input.length;
  let h2 = 0x41c6ce57 ^ input.length;
  for (let i = 0; i < input.length; i++) {
    const ch = input.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return (h1 >>> 0).toString(16).padStart(8, '0') + (h2 >>> 0).toString(16).padStart(8, '0');
}
